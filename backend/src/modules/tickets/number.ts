// Номер заявки для людей: префикс типа и порядковый номер. Вынесен из
// controller.ts в отдельный модуль, чтобы тест мог уронить именно сборку
// ответа после коммита создания (подменой этого модуля), не трогая очередь.
export const ticketNumber = (prefix: string, seq: number) => `${prefix}-${String(seq).padStart(6, "0")}`;
